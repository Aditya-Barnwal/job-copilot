#!/usr/bin/env python3
"""Verify a list of candidate companies by hitting their ATS endpoints.

Prints YAML for those that return ≥1 role; commented stub for those that don't.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from jobcopilot.connectors import (
    GreenhouseConnector, LeverConnector, AshbyConnector,
)


CANDIDATES = [
    # (name, sector, connector, slug)
    ("Stripe", "fintech", "greenhouse", "stripe"),
    ("Plaid", "fintech", "greenhouse", "plaid"),
    ("Affirm", "fintech", "greenhouse", "affirm"),
    ("Robinhood", "fintech", "greenhouse", "robinhood"),
    ("Brex", "fintech", "greenhouse", "brex"),
    ("Mercury", "fintech", "greenhouse", "mercury"),
    ("Razorpay", "fintech", "lever", "razorpay"),
    ("CRED", "fintech", "lever", "cred"),
    ("Groww", "fintech", "lever", "groww"),
    ("Setu", "fintech", "lever", "setu"),
    ("Postman", "tech", "greenhouse", "postman"),
    ("DigitalOcean", "tech", "greenhouse", "digitalocean"),
    ("Datadog", "tech", "greenhouse", "datadog"),
    ("Cloudflare", "tech", "greenhouse", "cloudflare"),
    ("HashiCorp", "tech", "greenhouse", "hashicorp"),
    ("Mixpanel", "tech", "greenhouse", "mixpanel"),
    ("Twilio", "tech", "greenhouse", "twilio"),
    ("Asana", "tech", "greenhouse", "asana"),
    ("Notion", "tech", "ashby", "notion"),
    ("Vercel", "tech", "ashby", "vercel"),
    ("Linear", "tech", "ashby", "linear"),
    ("Ramp", "fintech", "ashby", "ramp"),
    ("Discord", "tech", "greenhouse", "discord"),
    ("Figma", "tech", "greenhouse", "figma"),
    ("Anthropic", "tech", "greenhouse", "anthropic"),
    ("ThoughtSpot", "tech", "greenhouse", "thoughtspot"),
    ("Freshworks", "tech", "greenhouse", "freshworks"),
    ("Hasura", "tech", "greenhouse", "hasura"),
]


def main() -> None:
    classes = {
        "greenhouse": GreenhouseConnector,
        "lever": LeverConnector,
        "ashby": AshbyConnector,
    }
    print("# Generated by scripts/verify_candidates.py")
    for name, sector, ctype, slug in CANDIDATES:
        Conn = classes[ctype]
        company = {"name": name, "sector": sector, "slug": slug}
        try:
            jobs = Conn().fetch(company)
            n = len(jobs)
            if n >= 1:
                print(f'  - {{ name: {name}, sector: {sector}, connector: {ctype}, '
                      f'slug: {slug}, verify: false, note: "verified live ({n} roles)" }}')
            else:
                print(f'  # FAIL {name} {ctype}:{slug} returned 0 roles')
        except Exception as exc:
            kind = type(exc).__name__
            print(f'  # FAIL {name} {ctype}:{slug} {kind}: {exc}')


if __name__ == "__main__":
    main()
